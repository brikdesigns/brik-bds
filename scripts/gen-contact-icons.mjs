#!/usr/bin/env node
/**
 * gen-contact-icons.mjs — Bundled contact-mark registry for BDS <ContactIcon>.
 *
 * Reads the 5 per-mark two-path masters in `components/ui/ContactIcon/icons/
 * *.svg` and emits `components/ui/ContactIcon/contact-icons.generated.ts`: a
 * map of mark → inner SVG markup (a `.bds-contact-icon__bg` path + a
 * `.bds-contact-icon__glyph` path). <ContactIcon> renders this inline so a
 * mark resolves synchronously with NO runtime fetch — the same offline
 * contract as the <Icon> Phosphor subset (#1002), <Logo> registry, and
 * <ServiceTag> glyph set (#1242).
 *
 * brik-bds#1716 split the original 10-platform <SocialIcon> into a 6-mark
 * social-only component (see `scripts/gen-social-icons.mjs`) and this
 * 5-mark contact component (message/email/website/calendar/phone) — contact
 * marks have no brand identity, so <ContactIcon> supports only `grayscale`
 * and `accent` tones (no `brand`).
 *
 * Unlike <Logo> (multi-fill brand art, never recolored — brand guidelines own
 * the color) and <ServiceTag> (single currentColor path), a ContactIcon
 * master carries two independently targetable paths:
 *   - `.bds-contact-icon__bg`    — the rounded-badge background, no baked fill.
 *     CSS targets it directly (`type="badge"` colors it; `type="glyph"` sets
 *     `fill: none`).
 *   - `.bds-contact-icon__glyph` — the mark, `fill="currentColor"` so it
 *     recolors via the inherited `color` (knocked-out white for `type="badge"`,
 *     the active tone for `type="glyph"` — see ContactIcon.css).
 *
 * Each source master is a 36×36 viewBox with exactly two `<path>` elements, no
 * hard-coded color other than the glyph's `currentColor`. We (a) strip the
 * `<svg>` wrapper and keep only the inner two paths — the component owns the
 * wrapper, size, and viewBox — and (b) verify the shape (exactly 2 paths, the
 * expected classes, no stray hard-coded fill on the background path) so a
 * malformed master can't silently ship un-recolorable.
 *
 * Modes:
 *   node scripts/gen-contact-icons.mjs           # write the registry
 *   node scripts/gen-contact-icons.mjs --check    # fail if committed file is stale (CI drift gate)
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const ICONS_DIR = path.join(REPO_ROOT, 'components', 'ui', 'ContactIcon', 'icons');
const OUTPUT_PATH = path.join(
  REPO_ROOT,
  'components',
  'ui',
  'ContactIcon',
  'contact-icons.generated.ts',
);

/**
 * Extract the two `<path>` elements of a master, dropping the `<svg>` wrapper
 * the component owns, and verify the badge/glyph split is intact.
 */
function innerMarkup(raw, file) {
  const svg = raw.trim();
  const paths = [...svg.matchAll(/<path\b[^>]*\/>/g)].map((m) => m[0]);
  if (paths.length !== 2) {
    throw new Error(`"${file}" must have exactly 2 <path> elements (bg + glyph), found ${paths.length}.`);
  }
  const [bg, glyph] = paths;

  if (!/class="bds-contact-icon__bg"/.test(bg)) {
    throw new Error(`"${file}" — first path must carry class="bds-contact-icon__bg".`);
  }
  if (/fill="/.test(bg)) {
    throw new Error(
      `"${file}" — background path must not hard-code a fill; CSS targets ` +
        `.bds-contact-icon__bg directly so the tag can recolor it.`,
    );
  }
  if (!/class="bds-contact-icon__glyph"/.test(glyph)) {
    throw new Error(`"${file}" — second path must carry class="bds-contact-icon__glyph".`);
  }
  if (!/fill="currentColor"/.test(glyph)) {
    throw new Error(
      `"${file}" — glyph path must use fill="currentColor" so it recolors via ` +
        `the inherited color (a hard-coded fill would break theming).`,
    );
  }

  return `${bg}\n${glyph}`;
}

function collect() {
  const files = fs
    .readdirSync(ICONS_DIR)
    .filter((f) => f.endsWith('.svg'))
    .sort();

  const svgs = {}; // mark (file basename) → inner svg markup
  for (const file of files) {
    const mark = file.slice(0, -'.svg'.length);
    svgs[mark] = innerMarkup(fs.readFileSync(path.join(ICONS_DIR, file), 'utf8'), file);
  }
  return svgs;
}

function render(svgs) {
  const banner = `// AUTO-GENERATED by scripts/gen-contact-icons.mjs — DO NOT EDIT BY HAND.
// Source: components/ui/ContactIcon/icons/*.svg. Regenerate: \`npm run gen:contact-icons\`.
// Inner SVG markup (a .bds-contact-icon__bg path + a .bds-contact-icon__glyph
// path) for each mark, bundled inline so <ContactIcon> resolves offline with
// no runtime fetch (brik-bds#1716).
`;

  const marks = Object.keys(svgs).sort();
  const entries = marks.map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(svgs[key])},`).join('\n');
  const union = marks.map((p) => `'${p}'`).join(' | ');

  return `${banner}
/** Mark (file basename, e.g. \`email\`) → inner SVG markup (bg path + glyph path). */
export const CONTACT_ICON_SVGS: Record<string, string> = {
${entries}
};

/** Every bundled mark — the set <ContactIcon> can resolve without a fetch. */
export type ContactIconPlatform = ${union};

/** Ordered list of every bundled mark. */
export const CONTACT_ICON_PLATFORMS = Object.keys(CONTACT_ICON_SVGS) as ContactIconPlatform[];
`;
}

const check = process.argv.includes('--check');
const output = render(collect());

if (check) {
  const current = fs.existsSync(OUTPUT_PATH) ? fs.readFileSync(OUTPUT_PATH, 'utf8') : '';
  if (current !== output) {
    console.error(
      'contact-icons.generated.ts is stale. Run `npm run gen:contact-icons` and commit the result.',
    );
    process.exit(1);
  }
  console.log('gen-contact-icons --check: registry is up to date.');
} else {
  fs.writeFileSync(OUTPUT_PATH, output);
  const count = Object.keys(collect()).length;
  console.log(`gen-contact-icons: wrote ${count} marks → ${path.relative(REPO_ROOT, OUTPUT_PATH)}`);
}
