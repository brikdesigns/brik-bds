/**
 * dist-assemble.mjs — concatenate the token CSS sources into the canonical part
 * of dist/tokens.css. Shared by build-dist-tokens.js (reads the working tree) and
 * verify-prefix-equivalence.mjs (reads a git ref), so the "before" and "after"
 * sides of the no-values-change proof are assembled by the same code.
 *
 * Order is load-bearing (see the notes in build-dist-tokens.js): later blocks
 * win on equal specificity.
 */

export const HEADER = '/* @brikdesigns/bds — Token Cascade (auto-generated, do not edit) */\n\n';

// Non-color mode overrides — one block per wired collection (BDS #340).
export const MODE_FILES = ['modes-borderwidth.css', 'modes-spacing.css', 'modes-typography.css', 'modes-borderradius.css'];

/**
 * @param {(relPath: string) => string | null} read  repo-relative path -> contents, or null if absent
 * @param {(msg: string) => void} [log]
 */
export function assembleCanonical(read, log = () => {}) {
  const need = (rel) => {
    const text = read(rel);
    if (text === null) throw new Error(`dist-assemble: missing ${rel}`);
    return text;
  };

  const figmaTokens = need('tokens/figma-tokens.css');
  const gapFills = need('tokens/gap-fills.css');

  // Dark mode tokens (generated by SD from Figma color/dark mode)
  const dark = read('tokens/figma-tokens-dark.css');
  let darkTokens = '';
  if (dark !== null) {
    darkTokens = '\n\n' + dark;
    log('  ✓ Including dark mode tokens');
  } else {
    log('  ⚠ No figma-tokens-dark.css found — run npm run build:sd-dark to generate');
  }

  // Brik brand theme — applied when consumer sets .theme-brand-brik on <body>
  const brand = read('tokens/theme-brand-brik.css');
  let themeBrandBrik = '';
  if (brand !== null) {
    themeBrandBrik = '\n\n' + brand;
    log('  ✓ Including Brik brand theme');
  }

  let modeOverrides = '';
  for (const file of MODE_FILES) {
    const text = read(`tokens/${file}`);
    if (text !== null) {
      modeOverrides += '\n\n' + text;
      log(`  ✓ Including ${file}`);
    }
  }

  // Elevation mode overrides — MUST concat AFTER gap-fills.css (see build-dist-tokens.js).
  const elevation = read('tokens/modes-elevation.css');
  let elevationMode = '';
  if (elevation !== null) {
    elevationMode = '\n\n' + elevation;
    log('  ✓ Including modes-elevation.css (post gap-fills)');
  }

  const layoutFluid = need('tokens/layout-fluid.css');
  const ratios = need('tokens/ratios.css');
  const fluidType = need('tokens/fluid-type.css');
  const animations = need('tokens/animations.css');

  return (
    HEADER + figmaTokens + darkTokens + themeBrandBrik + modeOverrides + '\n\n' + gapFills + elevationMode +
    '\n\n' + layoutFluid + '\n\n' + ratios + '\n\n' + fluidType + '\n\n' + animations
  );
}
