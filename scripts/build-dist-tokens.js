#!/usr/bin/env node
/**
 * Copy token CSS files to dist/ after Vite library build.
 * Called by: npm run build:lib (as the final step)
 *
 * Produces:
 *   dist/tokens.css  — figma-tokens.css + figma-tokens-dark.css + theme-brand-brik.generated.css + modes-*.css + gap-fills.css + modes-elevation.css + modes-width.css + layout-fluid.css + ratios.css + fluid-type.css + animations.css concatenated
 *   dist/bridge.css  — clean name ↔ Webflow internal name aliases
 *   dist/retired-token-names.json — { "--old-name": "--bds-new-name" } for guard tooling (ADR-043, #2711); the old names no longer resolve
 */
const fs = require('fs');
const path = require('path');

const TOKENS_DIR = path.join(__dirname, '../tokens');
const BUILD_DIR = path.join(__dirname, '../build/figma/css');
const DIST_DIR = path.join(__dirname, '../dist');

// Ensure dist exists (Vite should have created it, but be safe)
if (!fs.existsSync(DIST_DIR)) {
  fs.mkdirSync(DIST_DIR, { recursive: true });
}

// Copy SD build outputs to tokens/ (canonical location for submodule consumers)
const sdCopyMap = {
  'variables.css': 'figma-tokens.css',
  'variables-dark.css': 'figma-tokens-dark.css',
};
for (const [src, dest] of Object.entries(sdCopyMap)) {
  const srcPath = path.join(BUILD_DIR, src);
  if (fs.existsSync(srcPath)) {
    fs.copyFileSync(srcPath, path.join(TOKENS_DIR, dest));
    console.log(`  ✓ tokens/${dest} (from build)`);
  }
}

// Build tokens.css: the canonical token cascade (assembled by the shared
// dist-assemble.mjs), then the retired-name map beside it. The ADR-043 prefix
// bridge (old name -> `--bds-` alias) was removed in #2711: old names no longer
// resolve, and they leave dist/tokens.css, which brik-llm's token-name-guard
// reads as its allowlist.
//
// Concat order is load-bearing:
//   - Mode overrides (modes-borderwidth/spacing/typography/borderradius) override
//     tokens defined earlier in figma-tokens.css, so their order among themselves
//     is cosmetic (BDS #340).
//   - modes-elevation.css MUST trail gap-fills.css: the tokens it overrides
//     (--bds-shadow-*) are `:root`-scoped in gap-fills.css, and the bare
//     `[data-mode-elevation="flat"]` selector matches `:root`'s specificity, so on
//     html it only wins by later source order. (A `:root[data-mode-elevation]`
//     selector would win on specificity but forfeit subtree application, which
//     every other mode supports. See CASCADE.md.)
//   - modes-width.css trails gap-fills.css for the same reason: it re-points
//     --bds-content-width-xl, which gap-fills declares on `:root`. It is the one
//     hand-authored mode file (no Figma `width` collection; #959 AC3).
//   - layout-fluid.css (ADR-042) is generated by `npm run build:modes` but carries
//     no [data-mode-*] selector, just a :root block — same reason ratios.css and
//     fluid-type.css aren't mode files. fluid-type.css is hand-authored because
//     clamp() can't be a Figma Variable (brik-bds#959 / brik-client-portal#1350).
//   - animations.css is the shared keyframe library (bds-spin, bds-pulse, ...).
async function main() {
  const { assembleCanonical } = await import('./lib/dist-assemble.mjs');
  const { buildRetiredNames } = await import('./lib/bds-prefix.mjs');

  const read = (rel) => {
    const p = path.join(TOKENS_DIR, '..', rel);
    return fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
  };
  const canonical = assembleCanonical(read, console.log);

  fs.writeFileSync(path.join(DIST_DIR, 'tokens.css'), `${canonical}\n`);
  console.log('  ✓ dist/tokens.css');

  const { map: retired, missing } = buildRetiredNames(canonical);
  if (missing.length) {
    throw new Error(`retired names: ${missing.length} legacy name(s) have no declared --bds- target:\n  ${missing.join('\n  ')}`);
  }
  fs.writeFileSync(path.join(DIST_DIR, 'retired-token-names.json'), `${JSON.stringify(retired, null, 2)}\n`);
  console.log(`  ✓ dist/retired-token-names.json (${Object.keys(retired).length} names)`);

  // Copy bridge.css — sourced from tokens/compat/ (the alias-compat layer, held
  // out of the tier-direction scan set per ADR-035; still published as dist/bridge.css)
  const bridge = fs.readFileSync(path.join(TOKENS_DIR, 'compat', 'bridge.css'), 'utf8');
  fs.writeFileSync(path.join(DIST_DIR, 'bridge.css'), bridge);
  console.log('  ✓ dist/bridge.css');

  // Write page-base.css — opt-in body reset that wires html/body background
  // to var(--bds-page-primary). Import AFTER tokens.css and BEFORE any atmosphere
  // CSS so the cascade reads: tokens → page-base → atmosphere decoration.
  const pageBase = [
    '/* @brikdesigns/bds — Page base styles (opt-in) */',
    '/* Import after tokens.css and before any atmosphere CSS. */',
    'html, body {',
    '  background: var(--bds-page-primary);',
    '  color: var(--bds-text-primary);',
    '}',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(DIST_DIR, 'page-base.css'), pageBase);
  console.log('  ✓ dist/page-base.css');

  console.log('Token CSS build complete.');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
